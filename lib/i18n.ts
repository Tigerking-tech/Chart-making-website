/** 嵌套字典按点分 key 查找：dict[lang].a.b.c → dict.zh.a.b.c → key 原文（便于发现遗漏）。 */
function walk(obj: any, key: string): any {
  let cur = obj;
  for (const p of key.split('.')) {
    if (cur == null || typeof cur !== 'object' || !(p in cur)) return undefined;
    cur = cur[p];
  }
  return cur;
}

export function t(lang: Lang, key: string): any {
  const v = walk(dict[lang] || dict.zh, key);
  if (v !== undefined) return v;
  const v2 = walk(dict.zh, key);
  if (v2 !== undefined) return v2;
  return key;
}

/** 模板替换：把 "{n}" 这类占位替换为给定值，用于句子内插值。 */
export function tf(lang: Lang, key: string, vars: Record<string, string | number>): string {
  let s = String(t(lang, key));
  for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
  return s;
}

/** 图表类型 → 翻译名。 */
export function chartName(lang: Lang, id: string): string {
  return t(lang, 'chart.' + id);
}
/** 分组 key → 翻译名。 */
export function groupName(lang: Lang, gk: string): string {
  return t(lang, 'group.' + gk);
}
