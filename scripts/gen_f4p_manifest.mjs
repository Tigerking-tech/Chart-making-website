// 扫描 public/figures4papers，生成 lib/f4pManifest.ts
// 用于 /figures4papers 论文图表范例画廊页。保留原作者 Chen Liu 署名与 CC BY-NC 4.0 标注。
import fs from 'fs';
import path from 'path';

const ROOT = path.join(process.cwd(), 'public', 'figures4papers');
const REPO = 'https://github.com/ChenLiu-1996/figures4papers';

// 图类分类（按 plot 脚本 stem 映射）
const CAT = {
  bar: '柱状 / 分组柱状',
  line: '折线 / 曲线',
  radar: '雷达图',
  heatmap: '热力图',
  scatter: '散点 / 流形',
  concept: '概念 / 示意图',
  other: '其他',
};

// 每个 plot 脚本的分类（stem -> cat key）
const STEM_CAT = {
  plot_brute_force: 'bar',
  plot_correctness_by_category: 'bar',
  plot_correctness_by_subcategory: 'bar',
  plot_rewriting: 'line',
  plot_selfcorrection_math: 'line',
  plot_ablation: 'bar',
  plot_comparison: 'scatter',
  plot_comparison_Ablation: 'line',
  plot_comparison_GeneRegulatory: 'scatter',
  plot_comparison_Trajectory: 'scatter',
  diffusion_swiss_roll: 'scatter',
  plot_idea: 'concept',
  plot_illustration: 'concept',
  plot_bars: 'bar',
  raw_data: 'other',
  plot_comparison: 'scatter',
  plot_comparison_speed: 'scatter',
  plot_hole_manifold: 'scatter',
  plot_manifold: 'scatter',
  plot_sweep: 'line',
  plot_ablation2: 'line',
  plot_comparison_radar: 'radar',
  plot_concept: 'concept',
  plot_posttraining: 'line',
  plot_composition: 'heatmap',
  plot_trend: 'line',
};

function titleFor(stem) {
  return stem.replace(/^plot_/, '').replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
}

function rel(p) {
  return '/figures4papers/' + p;
}

const items = [];

// 1) figure_* 目录：脚本 + 对应图
const dirs = fs.readdirSync(ROOT).filter((d) => d.startsWith('figure_'));
for (const dir of dirs) {
  const figDir = path.join(ROOT, dir);
  const figuresDir = path.join(figDir, 'figures');
  const pngs = fs.existsSync(figuresDir)
    ? fs.readdirSync(figuresDir).filter((f) => f.endsWith('.png') && statSize(figuresDir, f) > 0)
    : [];
  const scripts = fs.readdirSync(figDir).filter((f) => f.startsWith('plot_') && f.endsWith('.py') && statSize(figDir, f) > 0);
  for (const sc of scripts) {
    const stem = sc.replace(/\.py$/, '');
    const catKey = STEM_CAT[stem] || STEM_CAT[stem.replace(/_\d+$/, '')] || 'other';
    // 匹配图片：同名 stem 或包含 stem
    let img = pngs.find((p) => p.replace(/\.png$/, '') === stem.replace(/^plot_/, '')) ||
              pngs.find((p) => p.includes(stem.replace(/^plot_/, ''))) || pngs[0] || null;
    items.push({
      id: `${dir}/${stem}`,
      title: titleFor(stem),
      category: catKey,
      categoryLabel: CAT[catKey],
      image: img ? rel(path.join(dir, 'figures', img)) : null,
      code: rel(path.join(dir, sc)),
      repo: `${REPO}/tree/main/${dir}`,
    });
  }
}

// 2) assets 目录：概念/示意图（无脚本）
const assetsDir = path.join(ROOT, 'assets');
if (fs.existsSync(assetsDir)) {
  for (const f of fs.readdirSync(assetsDir).filter((x) => x.endsWith('.png') && statSize(assetsDir, x) > 0)) {
    const stem = f.replace(/\.png$/, '');
    items.push({
      id: `assets/${stem}`,
      title: titleFor(stem).replace(/([a-z])([A-Z])/g, '$1 $2'),
      category: 'concept',
      categoryLabel: CAT.concept,
      image: rel(path.join('assets', f)),
      code: null,
      repo: `${REPO}/tree/main/assets`,
    });
  }
}

items.sort((a, b) => a.category.localeCompare(b.category) || a.title.localeCompare(b.title));

const out = `// AUTO-GENERATED by scripts/gen_f4p_manifest.mjs — do not edit by hand.
// 来源：Chen Liu (Yale) 的 figures4papers，许可 CC BY-NC 4.0（署名-非商业性使用）。
export interface F4PItem {
  id: string;
  title: string;
  category: string;
  categoryLabel: string;
  image: string | null;
  code: string | null;
  repo: string;
}
export const F4P_ITEMS: F4PItem[] = ${JSON.stringify(items, null, 2)};
export const F4P_SOURCE = {
  author: 'Chen Liu (Yale University)',
  repo: '${REPO}',
  license: 'CC BY-NC 4.0（署名-非商业性使用）',
  note: '原代码与图片版权归原作者所有；ChartForge 仅作集成展示，未改动原文件。',
};
`;

fs.writeFileSync(path.join(process.cwd(), 'lib', 'f4pManifest.ts'), out);
console.log(`generated ${items.length} items -> lib/f4pManifest.ts`);

function statSize(dir, f) {
  try { return fs.statSync(path.join(dir, f)).size; } catch { return 0; }
}
